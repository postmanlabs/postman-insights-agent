#!/usr/bin/env bash
#
# Checks the repository's licence rules (see ebpf/programs/README.md):
#   - The root LICENSE (Apache-2.0) covers every file, so no file carries an
#     SPDX line of its own, anywhere in the file.
#   - Each BPF program (ebpf/programs/*.bpf.c) declares "GPL" to the kernel,
#     which GPL-only helpers such as bpf_probe_read_user require.
#
# Usage: build-scripts/check-license-headers.sh
# Lists the files that break a rule and exits 1, or exits 0.
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"

# An SPDX line is a comment: the marker comes after nothing but a comment
# opener (//, #, /* or *), so mentions in strings and prose do not count.
spdx_line='^[[:space:]]*(//|#|/\*|\*)[[:space:]]*SPDX-License-Identifier:'

# The licence a BPF program declares to the kernel, e.g.
#   char LICENSE[] SEC("license") = "GPL";
license_decl='^[[:space:]]*char[[:space:]]+[A-Za-z_][A-Za-z0-9_]*[[:space:]]*\[\][[:space:]]*SEC\("license"\)[[:space:]]*=[[:space:]]*"[^"]*"[[:space:]]*;'

# Tracked files, and new ones not yet added, so the check also works before
# a commit.
files=$(git ls-files --cached --others --exclude-standard | sort -u)

bad=0
while IFS= read -r f; do
  [[ -z "$f" || ! -f "$f" ]] && continue
  case "$f" in
    # Generated by Gradle, with Gradle's own header; licence texts and test
    # data are not source.
    java-agent/gradlew | java-agent/gradlew.bat | java-agent/gradle/wrapper/* | */testdata/* | LICENSE* | */LICENSE*)
      continue ;;
    # Generated by bpftool from the build host's kernel.
    ebpf/programs/vmlinux.h)
      continue ;;
  esac
  if grep -qIE -- "$spdx_line" "$f"; then
    echo "$f: remove the SPDX line; the root LICENSE covers this file"
    bad=1
  fi
  if [[ "$f" == ebpf/programs/*.bpf.c ]]; then
    # Only a declaration at the start of a line counts, so a commented-out
    # one (// or *) does not.
    declared=$(grep -E "$license_decl" "$f" | grep -oE '"[^"]*"[[:space:]]*;' | grep -oE '"[^"]*"' || true)
    if [[ "$declared" != '"GPL"' ]]; then
      echo "$f: declares licence ${declared:-none} to the kernel, want one \"GPL\" declaration" | paste -sd ',' -
      bad=1
    fi
  fi
done <<<"$files"

if [[ "$bad" -ne 0 ]]; then
  echo "Licence headers: see build-scripts/check-license-headers.sh and ebpf/programs/README.md." >&2
  exit 1
fi
