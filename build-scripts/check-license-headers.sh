#!/usr/bin/env bash
#
# Checks the repository's licence rule (see ebpf/programs/README.md):
#   - The root LICENSE (Apache-2.0) covers every file, so files under it carry
#     no SPDX line of their own.
#   - Only the BPF sources (ebpf/programs/*.c and *.h) carry one, because
#     they are under (GPL-2.0-only OR BSD-2-Clause), except the Apache-2.0
#     ones listed below, and declare a GPL-compatible licence to the kernel:
#     "Dual BSD/GPL" for the dual-licensed ones.
#
# Usage: build-scripts/check-license-headers.sh
# Lists the files that break a rule and exits 1, or exits 0.
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"

apache='SPDX-License-Identifier: Apache-2.0'
dual='SPDX-License-Identifier: (GPL-2.0-only OR BSD-2-Clause)'

# BPF sources under Apache-2.0: libssl.bpf.c follows the design of OBI's
# Apache-2.0 libssl.c (OpenTelemetry eBPF Instrumentation).
apache_bpf=(
  ebpf/programs/libssl.bpf.c
)

# The licence strings the kernel treats as GPL-compatible
# (license_is_gpl_compatible in the kernel).
kernel_gpl='"(GPL|GPL v2|GPL and additional rights|Dual BSD/GPL|Dual MIT/GPL|Dual MPL/GPL)"'

is_apache_bpf() {
  local f
  for f in "${apache_bpf[@]}"; do
    [[ "$1" == "$f" ]] && return 0
  done
  return 1
}

# Tracked files, and new ones not yet added, so the check also works before
# a commit.
files=$(git ls-files --cached --others --exclude-standard | sort -u)

bad=0
while IFS= read -r f; do
  [[ -z "$f" || ! -f "$f" ]] && continue
  case "$f" in
    # Generated by Gradle, with Gradle's own header; licence texts and test
    # data are not source.
    java-agent/gradlew | java-agent/gradlew.bat | java-agent/gradle/wrapper/* | */testdata/* | LICENSE* | */LICENSE*)
      continue ;;
    # Generated by bpftool from the build host's kernel.
    ebpf/programs/vmlinux.h)
      continue ;;
    ebpf/programs/*.c | ebpf/programs/*.h)
      want=$dual
      is_apache_bpf "$f" && want=$apache
      if ! head -n 3 "$f" | grep -qF -- "$want"; then
        echo "$f: want \"$want\" in its first lines"
        bad=1
      fi
      if [[ "$f" == *.bpf.c ]]; then
        declared=$(grep -oE 'SEC\("license"\) = "[^"]*"' "$f" | grep -oE '"[^"]*"$' || true)
        if ! grep -qxE "$kernel_gpl" <<<"$declared"; then
          echo "$f: declares licence ${declared:-none} to the kernel, want a GPL-compatible one"
          bad=1
        elif [[ "$want" == "$dual" && "$declared" != '"Dual BSD/GPL"' ]]; then
          echo "$f: declares licence $declared to the kernel, want \"Dual BSD/GPL\""
          bad=1
        fi
      fi
      ;;
    *)
      if head -n 3 "$f" | grep -qF -- "$apache"; then
        echo "$f: remove the SPDX line; the root LICENSE covers this file"
        bad=1
      fi
      ;;
  esac
done <<<"$files"

if [[ "$bad" -ne 0 ]]; then
  echo "Licence headers: see build-scripts/check-license-headers.sh and ebpf/programs/README.md." >&2
  exit 1
fi
